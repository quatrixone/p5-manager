#!/usr/bin/env python3
"""Embed the bundled LZ4 profiles (profiles/index.json) as a C table."""

import json
import os
import sys


def c_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    index_path = sys.argv[1]
    base = os.path.dirname(index_path)
    with open(index_path, encoding="utf-8") as handle:
        entries = json.load(handle)

    out = sys.stdout
    out.write("/* Generated by tools/gen_profiles_c.py from profiles/index.json. Do not edit. */\n")
    out.write('#include "lzc_profiles.h"\n\n')
    for i, entry in enumerate(entries):
        with open(os.path.join(base, entry["file"]), "rb") as handle:
            data = handle.read()
        data.decode("utf-8")
        out.write(f"static const unsigned char profile_{i}[] = {{\n")
        for offset in range(0, len(data), 16):
            out.write("  " + ", ".join(f"0x{b:02x}" for b in data[offset:offset + 16]) + ",\n")
        out.write("};\n\n")

    out.write("const lzc_bundled_profile_t lzc_bundled_profiles[] = {\n")
    for i, entry in enumerate(entries):
        fields = [
            c_string(entry["id"]),
            c_string(entry["file"]),
            c_string(entry["label"]),
            c_string(entry["tested"]),
            c_string(",".join(entry.get("titleIds", []))),
            c_string(",".join(entry.get("names", []))),
            c_string(entry.get("engine", "")),
            f"profile_{i}",
            f"sizeof(profile_{i})",
        ]
        out.write("  { " + ", ".join(fields) + " },\n")
    out.write("};\n")
    out.write(f"const size_t lzc_bundled_profile_count = {len(entries)};\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
